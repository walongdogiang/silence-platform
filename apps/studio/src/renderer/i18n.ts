/** Explanation of a Risk Engine code in `lang`; null for a code the UI does not know yet. */
export function riskText(code: string, lang: Lang): RiskText | null {
  return (lang === "vi" ? RISK_VI : RISK_EN)[code] ?? RISK_EN[code] ?? null;
}

/** Codes explained in both languages (tests keep this in step with the policy). */
export function riskTextCodes(): { en: string[]; vi: string[] } {
  return { en: Object.keys(RISK_EN), vi: Object.keys(RISK_VI) };
}

/** `riskText` bound to the current UI language. */
export function useRiskText(): (code: string) => RiskText | null {
  const lang = useContext(LangContext);
  return (code) => riskText(code, lang);
}

/**
 * Engine escalation phrases (`agent/auto.rs`, English) in the UI language. Unknown text passes
 * through unchanged.
 */
export function escalationText(why: string, t: T): string {
  const w = why.trim();
  let m: RegExpExecArray | null;
  if (w === "tests failed after an edit") return t("why.testFail");
  if ((m = /^(\S+) failed (\d+) times$/.exec(w))) return t("why.toolFail", { tool: m[1], n: m[2] });
  if ((m = /^(\S+) repeated with the same input$/.exec(w))) return t("why.repeat", { tool: m[1] });
  if ((m = /^(\d+) steps without progress$/.exec(w))) return t("why.stall", { n: m[1] });
  if (w === "empty replies") return t("why.empty");
  if (w === "provider error, retrying stronger") return t("why.provider");
  if (w === "trouble in the last turn") return t("why.lastTurn");
  return w;
}
