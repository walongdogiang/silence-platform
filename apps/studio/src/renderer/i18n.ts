const DICT: Record<Lang, Record<MsgKey, string>> = { en, vi };

export function isLang(v: unknown): v is Lang {
  return v === "vi" || v === "en";
}

/** `t("auto.used", { usd: "$1" }, "vi")` → "Đã dùng $1". Unknown `{x}` stays as is. */
export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  const s = DICT[lang][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export type T = (key: MsgKey, vars?: Record<string, string | number>) => string;

/** Translator bound to one language (outside React, and in tests). */
export function translator(lang: Lang): T {
  return (key, vars) => translate(lang, key, vars);
}

export const LangContext = createContext<Lang>(DEFAULT_LANG);

/** Translator for the current UI language. */
export function useT(): T {
  return translator(useContext(LangContext));
}

/**
 * Engine escalation phrases (`agent/auto.rs`, English) in the UI language. Unknown text passes
 * through unchanged.
 */
export function escalationText(why: string, t: T): string {
  const w = why.trim();
  let m: RegExpExecArray | null;
  if (w === "tests failed after an edit") return t("why.testFail");
  if ((m = /^(\S+) failed (\d+) times$/.exec(w))) return t("why.toolFail", { tool: m[1], n: m[2] });
  if ((m = /^(\S+) repeated with the same input$/.exec(w))) return t("why.repeat", { tool: m[1] });
  if ((m = /^(\d+) steps without progress$/.exec(w))) return t("why.stall", { n: m[1] });
  if (w === "empty replies") return t("why.empty");
  if (w === "provider error, retrying stronger") return t("why.provider");
  if (w === "trouble in the last turn") return t("why.lastTurn");
  return w;
}
